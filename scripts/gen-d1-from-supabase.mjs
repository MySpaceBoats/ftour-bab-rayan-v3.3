// Generates the D1 schema + column metadata for the Supabase tables from PostgREST's OpenAPI document.
// Outputs: worker/d1/schema.generated.sql, worker/d1/meta.generated.json, worker/d1-meta.generated.ts
// D1 table names are prefixed (t_) so they never collide with the legacy snapshot tables already in D1.
// Usage: node --env-file=.env.local scripts/gen-d1-from-supabase.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const { SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY: KEY } = process.env;
if (!SUPABASE_URL || !KEY) { console.error("SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY missing"); process.exit(1); }

// Tables already served by a hand-written D1 module (never routed through the generic adapter).
const CUSTOM = new Set([
    "gallery_albums", "gallery_photos", "blog_posts", "blog_post_likes", "ftour_team_members", "contact_messages",
    "partner_leads", "election_settings", "manager_candidates", "manager_votes", "donations",
]);
// Not generated: identity stays in Supabase (see migration plan).
const SKIP = new Set(["users", "user_roles"]);

const api = await (await fetch(`${SUPABASE_URL}/rest/v1/`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })).json();
const defs = api.definitions;

// ON DELETE CASCADE edges, read from the repo's SQL: { child_table: { child_col: parent_table } }
const cascades = {};
for (const dir of ["supabase", "supabase/migrations"]) {
    let files = [];
    try { files = readdirSync(dir).filter(f => f.endsWith(".sql")).map(f => `${dir}/${f}`); } catch {}
    for (const f of files) {
        let table = null;
        for (const line of readFileSync(f, "utf8").split("\n")) {
            const c = line.match(/CREATE TABLE(?: IF NOT EXISTS)?\s+(?:public\.)?"?([a-z_]+)"?/i);
            if (c) table = c[1];
            const alter = line.match(/ALTER TABLE\s+(?:public\.)?([a-z_]+)/i);
            if (alter) table = alter[1];
            const m = line.match(/^\s*(?:ADD COLUMN(?: IF NOT EXISTS)?\s+)?"?([a-z_]+)"?\s+[A-Za-z0-9_()]+.*REFERENCES\s+(?:public\.)?([a-z_]+)\s*\([a-z_]+\).*ON DELETE CASCADE/i);
            const fk = line.match(/FOREIGN KEY\s*\(([a-z_]+)\)\s*REFERENCES\s+(?:public\.)?([a-z_]+).*ON DELETE CASCADE/i);
            const hit = m ?? fk;
            if (hit && table) (cascades[table] ??= {})[hit[1]] = hit[2];
        }
    }
}

const UUID = "(lower(hex(randomblob(4)))||'-'||lower(hex(randomblob(2)))||'-4'||substr(lower(hex(randomblob(2))),2)||'-'||substr('89ab',abs(random())%4+1,1)||substr(lower(hex(randomblob(2))),2)||'-'||lower(hex(randomblob(6))))";
const NOW = "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))";

function kind(p) {
    const f = p.format ?? "";
    if (p.type === "boolean") return "bool";
    if (p.type === "array" || f === "jsonb" || f === "json") return "json";
    if (p.type === "integer") return "int";
    if (p.type === "number") return "num";
    return "text";
}
const sqlType = k => ({ bool: "INTEGER", int: "INTEGER", num: "REAL", json: "TEXT", text: "TEXT" })[k];

function dflt(p, k) {
    const d = p.default;
    if (d === undefined || d === null || d === "NULL") return null;
    const s = String(d);
    if (/^nextval/.test(s)) return null;
    if (s === "gen_random_uuid()") return UUID;
    if (/^now\(\)|CURRENT_TIMESTAMP/i.test(s)) return NOW;
    if (/^\(now\(\) \+ '(\d+) days'::interval\)$/.test(s)) return `(strftime('%Y-%m-%dT%H:%M:%fZ','now','+${s.match(/'(\d+) days'/)[1]} days'))`;
    if (s === "true") return "1";
    if (s === "false") return "0";
    if (k === "int" || k === "num") return Number.isFinite(Number(s)) ? s : null;
    if (k === "json") return /^\[\]|\{\}|'\[\]'|'\{\}'/.test(s) ? "'[]'" : null;
    return `'${s.replace(/::[a-z ]+$/, "").replace(/^'|'$/g, "").replace(/'/g, "''")}'`;
}

const meta = {};
const ddl = ["-- GENERATED by scripts/gen-d1-from-supabase.mjs. Do not edit.", "-- Apply: wrangler d1 execute <db> --remote --file worker/d1/schema.generated.sql"];
const skipped = [];
for (const [name, def] of Object.entries(defs)) {
    const cols = Object.entries(def.properties);
    const pk = cols.filter(([, p]) => /<pk\/>/.test(p.description ?? "")).map(([c]) => c);
    if (CUSTOM.has(name) || SKIP.has(name) || pk.length === 0) { skipped.push(name); continue; }
    const required = new Set(def.required ?? []);
    const fks = [];
    const lines = [];
    for (const [c, p] of cols) {
        const k = kind(p);
        const m = (p.description ?? "").match(/<fk table='([a-z_]+)' column='([a-z_]+)'\/>/);
        if (m) fks.push({ col: c, ref: m[1], refCol: m[2] });
        const isSerial = pk.length === 1 && pk[0] === c && k === "int";
        let line = `  "${c}" ${sqlType(k)}`;
        if (isSerial) line += " PRIMARY KEY AUTOINCREMENT";
        else {
            const d = dflt(p, k);
            if (required.has(c) && d === null) line += " NOT NULL";
            else if (required.has(c)) line += ` NOT NULL DEFAULT ${d}`;
            else if (d !== null) line += ` DEFAULT ${d}`;
            if (pk.length === 1 && pk[0] === c) line += " PRIMARY KEY";
            if (p.enum) line += ` CHECK ("${c}" IS NULL OR "${c}" IN (${p.enum.map(e => `'${String(e).replace(/'/g, "''")}'`).join(",")}))`;
        }
        lines.push(line);
    }
    if (pk.length > 1) lines.push(`  PRIMARY KEY (${pk.map(c => `"${c}"`).join(", ")})`);
    ddl.push(`CREATE TABLE IF NOT EXISTS "t_${name}" (\n${lines.join(",\n")}\n);`);
    for (const fk of fks) ddl.push(`CREATE INDEX IF NOT EXISTS "idx_t_${name}_${fk.col}" ON "t_${name}"("${fk.col}");`);
    meta[name] = {
        cols: Object.fromEntries(cols.map(([c, p]) => [c, kind(p)])),
        pk,
        fks: fks.filter(f => !SKIP.has(f.ref) && !CUSTOM.has(f.ref)),
        cascade: cascades[name] ?? {},
        hasUpdatedAt: cols.some(([c]) => c === "updated_at"),
    };
}

writeFileSync("worker/d1/schema.generated.sql", ddl.join("\n") + "\n");
writeFileSync("worker/d1/meta.generated.json", JSON.stringify(meta, null, 1) + "\n");
writeFileSync(
    "worker/d1-meta.generated.ts",
    `// GENERATED by scripts/gen-d1-from-supabase.mjs. Do not edit.\nimport meta from "./d1/meta.generated.json";\n\nexport type ColKind = "int" | "num" | "bool" | "json" | "text";\nexport interface TableMeta {\n  cols: Record<string, ColKind>;\n  pk: string[];\n  fks: { col: string; ref: string; refCol: string }[];\n  cascade: Record<string, string>;\n  hasUpdatedAt: boolean;\n}\nexport const META = meta as unknown as Record<string, TableMeta>;\n`
);
console.log(`${Object.keys(meta).length} tables generated; skipped: ${skipped.join(", ")}`);
